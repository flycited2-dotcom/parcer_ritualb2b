"""Нормализация category → client_type для ритуальной ниши.

`category` приходит из источников в разном написании (тег OSM, рубрика VK,
запрос Я.Карт). Здесь приводим её к канонической client_type для группировки
и раскраски в Excel. Грубая классификация (ритуал / флористика / шум) делается
в `parsers/vk_filter.py` по ключевым словам названия.
"""

CANONICAL = [
    "ритуальное агентство",
    "похоронное бюро",
    "ритуальный магазин",
    "мастерская памятников",
    "кладбищенские услуги",
    "флористика",
]

DEFAULT = "прочее"

# Ключ ищется как подстрока в нижнем регистре. Порядок важен: специфичные
# стемы стоят раньше общих (например «памятник» раньше «ритуал»).
ALIASES = {
    # мастерская памятников
    "памятник": "мастерская памятников",
    "надгроб": "мастерская памятников",
    "ограды на могил": "мастерская памятников",
    "гранитная мастерская": "мастерская памятников",
    "stonemason": "мастерская памятников",
    # кладбищенские услуги / крематорий
    "кладбищ": "кладбищенские услуги",
    "крематор": "кладбищенские услуги",
    "кремац": "кладбищенские услуги",
    "crematorium": "кладбищенские услуги",
    "благоустройство могил": "кладбищенские услуги",
    # похоронное бюро
    "похоронное бюро": "похоронное бюро",
    "похоронный дом": "похоронное бюро",
    "похоронная служба": "похоронное бюро",
    "funeral hall": "похоронное бюро",
    "funeral_hall": "похоронное бюро",
    # ритуальный магазин
    "ритуальный магазин": "ритуальный магазин",
    "ритуальные товар": "ритуальный магазин",
    "ритуальная атрибутика": "ритуальный магазин",
    "венк": "ритуальный магазин",
    "гроб": "ритуальный магазин",
    # ритуальное агентство / полный цикл (общий ритуал — последним)
    "ритуальное агентство": "ритуальное агентство",
    "ритуальные услуги": "ритуальное агентство",
    "похорон": "ритуальное агентство",
    "ритуал": "ритуальное агентство",
    "funeral_directors": "ритуальное агентство",
    "funeral directors": "ритуальное агентство",
    # флористика
    "флорист": "флористика",
    "цветочн": "флористика",
    "букет": "флористика",
    "цветы": "флористика",
}


def normalize(category: str) -> str:
    """Привести category к канонической client_type. Пустое → 'прочее'."""
    if not category:
        return DEFAULT
    cat = category.lower().strip()
    if cat in ALIASES:
        return ALIASES[cat]
    for key, val in ALIASES.items():
        if key in cat:
            return val
    return DEFAULT
