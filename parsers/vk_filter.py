"""Классификатор VK-групп и прочих источников: ритуал / флористика / noise / ambiguous.

Решение по двум полям:
  - name (название группы/организации)
  - activity (рубрика VK / тег источника)

Логика (приоритет ритуала над флористикой):
  есть RITUAL_KEYWORD       → "ритуал"
  иначе есть FLORIST_KEYWORD → "флористика"
  иначе есть NOISE_KEYWORD   → "noise" (отбрасываем)
  иначе                      → "ambiguous" (сохраняем с пометкой needs_review)

Консервативно: при сомнении — "ambiguous" (на ручную проверку), а не "noise"
и не чистый ритуал. Приоритет — качество базы для обзвона.
"""

RITUAL_KEYWORDS = (
    # стемы (без окончания) — ловят разные словоформы
    "ритуал",        # ритуальный, ритуальные
    "похорон",       # похоронный, похороны, похоронное
    "погреб",        # погребение, погребальный
    "венк",          # венок, венки, венков
    "гроб",          # гроб, гробы
    "надгроб",       # надгробие, надгробный
    "памятник",      # памятник на могилу
    "кладбищ",       # кладбище, кладбищенский
    "кремац",        # кремация
    "кремат",        # крематорий
    "мемориал",      # мемориал, мемориальный
    "усопш",         # усопший
    "отпеван",       # отпевание
    "поминк",        # поминки
    "поминальн",     # поминальные товары
    "траурн",        # траурный
    "эпитафи",       # эпитафия
)

FLORIST_KEYWORDS = (
    "флорист",       # флорист, флористика
    "цветочн",       # цветочный магазин
    "букет",         # букеты
    "цветы",         # цветы (перенесён сюда из noise отельной версии)
)

NOISE_KEYWORDS = (
    # event / торжества (не похоронные)
    "свадебн", "свадьб", "банкет", "торт", "праздничн", "юбилей",
    # детское (false-positive «корзинка», «памятка»)
    "детск", "развивающ", "детский сад",
    # коммерция/услуги вне ниши
    "автозапчаст", "автосервис", "недвижимост", "риелтор", "юрист", "адвокат",
    "стоматолог", "клиник", "фитнес", "красот", "парикмахер", "косметолог",
    "ремонт квартир", "натяжн", "пластиковые окна",
    # коммьюнити / контент
    "знакомств", "чат", "юмор", "афиша", "объявлен", "новости",
)


def classify(name: str, activity: str = "") -> str:
    """'ритуал' | 'флористика' | 'noise' | 'ambiguous'."""
    t = f"{(name or '').lower()} | {(activity or '').lower()}"
    if any(kw in t for kw in RITUAL_KEYWORDS):
        return "ритуал"
    if any(kw in t for kw in FLORIST_KEYWORDS):
        return "флористика"
    if any(kw in t for kw in NOISE_KEYWORDS):
        return "noise"
    return "ambiguous"
